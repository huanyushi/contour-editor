import { expect, test } from '@playwright/test'
import { openSection, selectObject, showCanvas } from './navigation'
import { clickPoint, loadBoxFixture, savedProject, screenPoint } from './selection'

test('segments connect existing points without creating endpoints or duplicate lines', async ({
  page,
}) => {
  await page.goto('/')
  await loadBoxFixture(page)
  await page.getByRole('button', { name: '独立点工具', exact: true }).click()
  await clickPoint(page, -1, -2)
  await clickPoint(page, 1, -2)
  const before = await savedProject(page)
  const original = await page.getByTestId('contour-path').getAttribute('d')
  await page.getByRole('button', { name: '线段工具', exact: true }).click()
  await clickPoint(page, 0, -3)
  await clickPoint(page, -1, -2)
  await clickPoint(page, -1, -2)
  expect((await savedProject(page)).document.connections ?? []).toHaveLength(0)
  await clickPoint(page, 1, -2)
  let project = await savedProject(page)
  expect(project.document.vertices).toEqual(before.document.vertices)
  expect(project.document.markers).toEqual(before.document.markers)
  expect(project.document.connections).toHaveLength(1)
  expect(project.version).toBe(2)
  await expect(page.getByTestId('contour-path')).toHaveAttribute('d', original!)
  await expect(page.getByTestId('contour-path')).not.toHaveAttribute('fill', 'none')
  await clickPoint(page, 1, -2)
  await clickPoint(page, -1, -2)
  expect((await savedProject(page)).document.connections).toHaveLength(1)
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  expect((await savedProject(page)).document.connections ?? []).toHaveLength(0)
  await page.getByRole('button', { name: '重做', exact: true }).click()
  await clickPoint(page, -2, 0)
  await clickPoint(page, 2, 2)
  project = await savedProject(page)
  expect(project.document.connections).toHaveLength(2)
  expect(project.document.vertices).toHaveLength(4)
  expect(project.document.markers).toHaveLength(2)
  await selectObject(page, '选择独立路径段 1')
  await openSection(page, '几何')
  await page.getByLabel('经过点实部 Re', { exact: true }).fill('0')
  await page.getByLabel('经过点虚部 Im', { exact: true }).fill('-1')
  await page.getByRole('button', { name: '应用经过点', exact: true }).click()
  await expect(page.getByRole('heading', { name: '圆弧属性', exact: true })).toBeVisible()
  project = await savedProject(page)
  expect(project.document.connections?.[0].kind).toBe('arc')
  const json = Buffer.from(JSON.stringify(project))
  await page
    .getByLabel('打开项目文件')
    .setInputFiles({ name: 'segments.json', mimeType: 'application/json', buffer: json })
  await expect(page.getByText('已打开 segments.json', { exact: true })).toBeVisible()
  expect((await savedProject(page)).document.connections).toEqual(project.document.connections)
})

test('point and formula tools reuse existing objects and immediately allow dragging them', async ({
  page,
}) => {
  await page.goto('/')
  await loadBoxFixture(page)
  await page.getByRole('button', { name: '独立点工具', exact: true }).click()
  await clickPoint(page, -1, -2)
  await clickPoint(page, -1, -2)
  expect((await savedProject(page)).document.markers).toHaveLength(1)
  await showCanvas(page)
  const point = await screenPoint(page, -1, -2)
  await page.mouse.move(point.x, point.y)
  await page.mouse.down()
  await page.mouse.move(point.x + 40, point.y, { steps: 5 })
  await page.mouse.up()
  expect((await savedProject(page)).document.markers[0]).toMatchObject({ re: 0, im: -2 })
  await page.getByRole('button', { name: '公式工具', exact: true }).click()
  await clickPoint(page, 0, 3)
  await clickPoint(page, 0, 3)
  expect((await savedProject(page)).document.formulas).toHaveLength(1)
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  expect((await savedProject(page)).document.formulas).toHaveLength(0)
  await page.getByRole('button', { name: '重做', exact: true }).click()
  await showCanvas(page)
  const formula = (await page.locator('[data-testid^="formula-"]').boundingBox())!
  const x = formula.x + formula.width / 2,
    y = formula.y + formula.height / 2
  await page.mouse.move(x, y)
  await page.mouse.down()
  await page.mouse.move(x + 40, y - 40, { steps: 5 })
  await page.mouse.up()
  const moved = await savedProject(page)
  expect(moved.document.formulas).toHaveLength(1)
  expect(moved.document.formulas[0]).toMatchObject({ re: 1, im: 4 })
  await page.getByRole('button', { name: '添加顶点', exact: true }).click()
  await clickPoint(page, -2, 0)
  expect((await savedProject(page)).document.vertices).toHaveLength(4)
})
