import { render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it } from 'vitest'
import App from './App'

describe('history controls and compact inspector', () => {
  it('undoes and redoes a coordinate edit with buttons and shortcuts', async () => {
    const user = userEvent.setup()
    render(<App />)
    expect(screen.getByRole('button', { name: '撤销' })).toBeDisabled()
    const original = screen.getByTestId('contour-path').getAttribute('d')
    await user.clear(screen.getByLabelText('实部 Re'))
    await user.type(screen.getByLabelText('实部 Re'), '1.5')
    await user.click(screen.getByRole('button', { name: '应用坐标' }))
    const edited = screen.getByTestId('contour-path').getAttribute('d')
    expect(edited).not.toBe(original)
    await user.click(screen.getByRole('button', { name: '撤销' }))
    expect(screen.getByTestId('contour-path')).toHaveAttribute('d', original)
    await user.keyboard('{Control>}{Shift>}z{/Shift}{/Control}')
    expect(screen.getByTestId('contour-path')).toHaveAttribute('d', edited)
    await user.keyboard('{Control>}z{/Control}')
    expect(screen.getByTestId('contour-path')).toHaveAttribute('d', original)
    await user.click(screen.getByRole('button', { name: '重做' }))
    expect(screen.getByLabelText('实部 Re')).toHaveValue('1.5')
    await user.keyboard('{Meta>}z{/Meta}')
    expect(screen.getByTestId('contour-path')).toHaveAttribute('d', original)
    await user.keyboard('{Meta>}{Shift>}z{/Shift}{/Meta}')
    expect(screen.getByTestId('contour-path')).toHaveAttribute('d', edited)
  })
  it('leaves input text shortcuts alone and does not undo document edits while typing', async () => {
    const user = userEvent.setup()
    render(<App />)
    await user.clear(screen.getByLabelText('实部 Re'))
    await user.type(screen.getByLabelText('实部 Re'), '2{Enter}')
    const edited = screen.getByTestId('contour-path').getAttribute('d')
    await user.keyboard('{Control>}z{/Control}')
    expect(screen.getByTestId('contour-path')).toHaveAttribute('d', edited)
    expect(screen.getByRole('button', { name: '撤销' })).toBeEnabled()
  })
  it('selects from the object panel and displays the corresponding properties', async () => {
    const user = userEvent.setup()
    render(<App />)
    expect(screen.queryByRole('button', { name: '选择路径段 2' })).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: '对象列表' }))
    const list = screen.getByRole('complementary', { name: '对象列表' })
    await user.click(within(list).getByRole('button', { name: '选择路径段 2' }))
    expect(screen.getByRole('heading', { name: '直线属性' })).toBeVisible()
    expect(screen.getByLabelText('经过点实部 Re')).toBeVisible()
    expect(screen.queryByRole('textbox', { name: 'LaTeX 标签' })).not.toBeInTheDocument()
  })
  it('retains an unsubmitted label draft when opening and closing the object list', async () => {
    const user = userEvent.setup()
    render(<App />)
    await user.click(screen.getByText('标签', { exact: true }))
    await user.clear(screen.getByLabelText('LaTeX 标签'))
    await user.type(screen.getByLabelText('LaTeX 标签'), 'a+b')
    expect(screen.queryByRole('textbox', { name: '实部 Re' })).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: '对象列表' }))
    await user.click(screen.getByRole('button', { name: '收起对象列表' }))
    await user.click(screen.getByRole('button', { name: '收起属性面板' }))
    await user.click(screen.getByRole('button', { name: '展开属性面板' }))
    await user.click(screen.getByRole('button', { name: '视图设置' }))
    await user.click(screen.getByRole('button', { name: '关闭视图设置' }))
    expect(screen.getByLabelText('LaTeX 标签')).toHaveValue('a+b')
    expect(screen.getByRole('button', { name: '撤销' })).toBeDisabled()
    await user.click(screen.getByRole('button', { name: '应用标签' }))
    await user.click(screen.getByRole('button', { name: '撤销' }))
    expect(screen.getByTestId('label-a')).toHaveAttribute('aria-label', '-R')
  })
})
