import { fireEvent, render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it } from 'vitest'
import App from './App'
import { openMore, openSection, selectObject } from '../test/navigation'

describe('workspace properties', () => {
  it('does not record resetting an untouched automatic label position', async () => {
    const user = userEvent.setup()
    render(<App />)
    await user.click(screen.getByRole('button', { name: '反转方向' }))
    await user.click(screen.getByRole('button', { name: '撤销' }))
    await openSection(user, '标签')
    await user.click(screen.getByRole('button', { name: '重置标签位置' }))
    expect(screen.getByRole('button', { name: '重做' })).toBeEnabled()
    expect(screen.getByRole('button', { name: '撤销' })).toBeDisabled()
  })
  it('retains unsubmitted TeX when label appearance is edited', async () => {
    const user = userEvent.setup()
    render(<App />)
    await openSection(user, '标签')
    await user.clear(screen.getByLabelText('LaTeX 标签'))
    await user.type(screen.getByLabelText('LaTeX 标签'), 'a+b')
    const slider = screen.getByRole('slider', { name: '标签字号' })
    fireEvent.change(slider, { target: { value: '40' } })
    expect(screen.getByTestId('label-a')).toHaveAttribute('aria-label', 'z_{1}')
    expect(screen.getByLabelText('LaTeX 标签')).toHaveValue('a+b')
    await user.click(screen.getByRole('button', { name: '应用标签' }))
    expect(screen.getByTestId('label-a')).toHaveAttribute('aria-label', 'a+b')
  })
  it('switches to contextual arc properties and displays derived radius and angles', async () => {
    const user = userEvent.setup()
    render(<App />)
    await openMore(user)
    await user.click(screen.getByRole('button', { name: '半圆示例' }))
    expect(screen.getByRole('heading', { name: '圆弧属性' })).toBeVisible()
    await openSection(user, '圆弧参数')
    expect(screen.getByLabelText('圆弧半径')).toHaveTextContent('2')
    expect(screen.getByLabelText('圆弧转角')).toHaveTextContent('180')
    await selectObject(user, '选择顶点 z1')
    expect(screen.getByRole('heading', { name: '顶点属性' })).toBeVisible()
    expect(screen.queryByLabelText('经过点虚部 Im')).not.toBeInTheDocument()
  })
  it('applies an editable mathematical label to a vertex and rejects invalid source', async () => {
    const user = userEvent.setup()
    render(<App />)
    await openSection(user, '标签')
    await user.clear(screen.getByLabelText('LaTeX 标签'))
    await user.paste('\\psi')
    await user.click(screen.getByRole('button', { name: '应用标签' }))
    expect(screen.getByTestId('label-a')).toHaveAttribute('aria-label', '\\psi')
    await user.clear(screen.getByLabelText('LaTeX 标签'))
    await user.paste('\\frac{')
    await user.click(screen.getByRole('button', { name: '应用标签' }))
    expect(screen.getByRole('alert')).toHaveTextContent('公式错误')
    expect(screen.getByTestId('label-a')).toHaveAttribute('aria-label', '\\psi')
  })
  it('changes fill independently from closure', async () => {
    const user = userEvent.setup()
    render(<App />)
    await user.click(screen.getByRole('button', { name: '围道属性' }))
    expect(document.querySelectorAll('.drawing-tools .active')).toHaveLength(1)
    expect(screen.getByRole('button', { name: '选择工具' })).toHaveAttribute('aria-pressed', 'true')
    expect(screen.getByRole('button', { name: '围道属性' })).not.toHaveAttribute('aria-pressed')
    expect(screen.getByRole('heading', { name: '围道与填充' })).toBeVisible()
    await user.selectOptions(screen.getByLabelText('填充形式'), 'hatch')
    expect(screen.getByTestId('contour-path')).toHaveAttribute('fill', 'url(#contour-hatch)')
    await user.selectOptions(screen.getByLabelText('填充形式'), 'none')
    expect(screen.getByTestId('contour-path')).toHaveAttribute('fill', 'none')
    expect(screen.getByRole('checkbox', { name: '闭合围道' })).toBeChecked()
  })
  it('creates and removes an independent point without changing contour geometry', async () => {
    const user = userEvent.setup()
    render(<App />)
    const original = screen.getByTestId('contour-path').getAttribute('d')
    await user.click(screen.getByRole('button', { name: '独立点工具' }))
    await openMore(user)
    await user.click(screen.getByRole('button', { name: '在原点添加独立点' }))
    expect(screen.getByRole('heading', { name: '标记点属性' })).toBeVisible()
    expect(screen.getByTestId('contour-path')).toHaveAttribute('d', original)
    await user.click(screen.getByRole('button', { name: '删除标记点' }))
    await user.click(screen.getByRole('button', { name: '对象列表' }))
    expect(screen.queryByRole('button', { name: /^选择标记点/ })).not.toBeInTheDocument()
  })
})
